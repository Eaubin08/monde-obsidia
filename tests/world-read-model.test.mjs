import {test} from 'node:test'
import assert from 'node:assert/strict'
import {projectWorldObject,worldObjectKey} from '../src/worldObjectContract.ts'
import {buildWorldReadModel,buildWorldGraph,createWorldContext} from '../src/worldReadModel.ts'
const obj=(org,domain,kind,id,relations=[],available=true)=>projectWorldObject({organizationId:org,domain,kind,id,label:id,sourceId:'SOURCE_'+domain,available,truth:'DECLARED',pattern:'WORKSPACE',relations,capabilities:['READ_'+domain],evidenceRefs:['EVIDENCE_'+id]})
const relation=(domain,kind,id,sourceId)=>({kind:'LINK',target:{domain,kind,id},sourceId,status:'RESOLVED',evidenceRefs:['EDGE_PROOF']})
test('read model enforces tenant boundary and keeps duplicate identity unresolved',()=>{
 const a=obj('CSSA','BUSINESS','CASE','A'),b=obj('OTHER','BUSINESS','CASE','B')
 const model=buildWorldReadModel('CSSA',[a,b,a])
 assert.equal(model.objects.length,0)
 assert.equal(model.unknowns.length,1)
 assert.equal(model.governance.authority,'NONE')
})
test('graph resolves only explicit relations backed by available source and target',()=>{
 const match=obj('CSSA','SPORT','OPERATION','m',[relation('OPS','TASK','t','SOURCE_OPS')])
 const task=obj('CSSA','OPS','TASK','t')
 const model=buildWorldReadModel('CSSA',[match,task])
 const graph=buildWorldGraph(model)
 assert.equal(graph.edges.length,1)
 assert.equal(graph.edges[0].status,'RESOLVED')
 assert.deepEqual(graph.edges[0].evidenceRefs,['EDGE_PROOF'])
 const ctx=createWorldContext(model,graph,worldObjectKey(match))
 assert.equal(ctx.focus?.identity.id,'m')
 assert.equal(ctx.relations[0].object?.identity.id,'t')
 assert.deepEqual(ctx.capabilities.sort(),['READ_OPS','READ_SPORT'])
 assert.equal(ctx.governance.decisionAuthority,'KX108_ONLY')
})
test('missing source or target never becomes a proven connection',()=>{
 const match=obj('CSSA','SPORT','OPERATION','m',[relation('OPS','TASK','missing','SOURCE_OPS')])
 const model=buildWorldReadModel('CSSA',[match])
 const graph=buildWorldGraph(model)
 assert.equal(graph.edges[0].status,'SOURCE_UNKNOWN')
 assert.deepEqual(graph.edges[0].evidenceRefs,[])
 const ctx=createWorldContext(model,graph,worldObjectKey(match))
 assert.equal(ctx.relations[0].object,null)
 assert.equal(ctx.unknowns.some(x=>x.startsWith('SOURCE_UNKNOWN:')),true)
})
test('unknown focus fails closed without choosing another object',()=>{
 const a=obj('FACTORY','PRODUCTION','RESOURCE','machine-1')
 const model=buildWorldReadModel('FACTORY',[a])
 const graph=buildWorldGraph(model)
 const ctx=createWorldContext(model,graph,'missing')
 assert.equal(ctx.focus,null)
 assert.deepEqual(ctx.capabilities,[])
 assert.ok(ctx.unknowns.includes('FOCUS_UNKNOWN'))
})
test('unavailable object never leaks relations or capabilities',()=>{
 const a=obj('CSSA','CRM','ACTOR','actor',[relation('BUSINESS','CASE','d','SOURCE_BUSINESS')],false)
 const model=buildWorldReadModel('CSSA',[a])
 const graph=buildWorldGraph(model)
 assert.equal(graph.edges.length,0)
 const ctx=createWorldContext(model,graph,worldObjectKey(a))
 assert.deepEqual(ctx.capabilities,[])
 assert.deepEqual(ctx.evidenceRefs,[])
})
